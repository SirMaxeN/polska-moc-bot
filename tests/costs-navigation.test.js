import test from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { mkdtempSync, rmSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Database } from '../src/storage/Database.js';
import { WarCalendar } from '../src/domain/WarCalendar.js';
import { ScoringService } from '../src/domain/ScoringService.js';
import { ReportService } from '../src/discord/ReportService.js';
import { CommandService } from '../src/discord/CommandService.js';
import { ResourceForm } from '../src/discord/ResourceForm.js';
const now = new Date('2026-10-13T13:00:00Z');
test('separate costs, private menu, all report navigation and cost lifecycle', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'costs-test-'));
  const calendar = new WarCalendar(), scoring = new ScoringService();
  const db = new Database(':memory:', calendar, dir);
  t.after(() => { db.close(); rmSync(dir, { recursive:true, force:true }); });
  const reports = new ReportService(calendar, scoring), commands = new CommandService(db, reports, scoring);
  const interaction = { id:'costs-1', guild_id:'22', member:{ user:{ id:'11', username:'Test' }, permissions:'0' }};
  const run = data => commands.handle({ ...interaction, type:2, data }, now);
  assert.equal(ResourceForm.open('11').data.components.length, 5);
  const form = await run({ name:'costs' });
  assert.deepEqual(form.data.components.map(row => row.component.value), ['200', '50']);
  const submit = values => commands.handle({ ...interaction, type:5, data:{ custom_id:'resources:11:save-costs', components:Object.entries(values).map(([custom_id,value]) => ({ type:18, component:{ custom_id,value }})) }}, now);
  await submit({ skill_cost_x5:'188', mount_cost:'40' });
  assert.equal(db.profile('22','11').mount_cost,40);
  assert.equal(db.snapshot('22',now).players.length,0);
  await submit({ skill_cost_x5:'180', mount_cost:'0' });
  assert.equal(db.profile('22','11').skill_cost_x5,188);
  await submit({ skill_cost_x5:'', mount_cost:'' });
  assert.equal(db.profile('22','11').mount_cost,40);
  db.update('22','11','Test',{mount_keys:2840},now);
  const days = scoring.player(db.profile('22','11'), db.snapshot('22',now).tech);
  assert.equal(days[1].total,71 * 1080 * 2);
  const start = await run({name:'start'});
  assert.equal(start.data.flags,64);
  const ids = start.data.components.flatMap(row=>row.components).map(button=>button.custom_id);
  for (const expected of ['resources:11:open','resources:11:costs','menu:11:help','menu:11:tech-show']) assert.ok(ids.includes(expected));
  for (const kind of ['player','clan','clan-details', 'clan-ultra']) {
    for (const players of [[],db.snapshot('22',now).players]) {
      const report=reports.render(kind,{players,tech:db.snapshot('22',now).tech},'11',now);
      const ids=report.components.flatMap(row=>row.components).map(button=>button.custom_id);
      for (const reportKind of ['player','clan','clan-details', 'clan-ultra']) assert.ok(ids.includes('report:11:'+reportKind+':0'));
      assert.ok(ids.includes('resources:11:open'));
      assert.equal(report.content,'');
    }
  }
  const stranger = await commands.handle({...interaction,type:3,data:{custom_id:'menu:99:tech-show'}},now);
  assert.match(stranger.data.content,/innego gracza/);
  const sunday=new Date('2026-10-19T00:00:00Z');
  db.snapshot('22',sunday);
  assert.equal(db.profile('22','11').mount_cost,40);
  assert.equal(db.profile('22','11').skill_cost_x5,188);
  await db.seasonReset('22','11',sunday,'reset-costs');
  assert.equal(db.profile('22','11').mount_cost,null);
  assert.equal(db.profile('22','11').skill_cost_x5,null);
});
test('old schema migration preserves data and makes one restorable backup', t => {
  const dir=mkdtempSync(join(tmpdir(),'migration-test-')), path=join(dir,'bot.sqlite'), backups=join(dir,'backups');
  t.after(()=>rmSync(dir,{recursive:true,force:true}));
  let db=new Database(path,new WarCalendar(),backups);
  db.update('22','11','Test',{skill_cost_x5:188,pets:28},now);
  db.updateTech('22','forge',12);
  db.db.exec('ALTER TABLE players DROP COLUMN mount_cost');
  db.close();
  db=new Database(path,new WarCalendar(),backups);
  assert.equal(db.profile('22','11').pets,28);
  assert.equal(db.profile('22','11').skill_cost_x5,188);
  assert.equal(db.profile('22','11').mount_cost,null);
  assert.equal(db.snapshot('22',now).tech.forge,12);
  db.close();
  const files=readdirSync(backups);
  assert.equal(files.length,1);
  const old=new DatabaseSync(join(backups,files[0]));
  assert.equal(old.prepare('SELECT pets FROM resources').get().pets,28);
  assert.ok(!old.prepare('PRAGMA table_info(players)').all().some(row=>row.name==='mount_cost'));
  old.close();
  db=new Database(path,new WarCalendar(),backups);db.close();
  assert.equal(readdirSync(backups).length,1);
});
